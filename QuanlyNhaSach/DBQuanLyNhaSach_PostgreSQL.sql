CREATE TABLE IF NOT EXISTS "NGUOIDUNG" (
    "MaND" varchar(10) NOT NULL,
    "Tendangnhap" varchar(10) NOT NULL,
    "Matkhau" varchar(60) NOT NULL,
    "Hoten" varchar(100) NULL,
    "SDT" varchar(10) NULL,
