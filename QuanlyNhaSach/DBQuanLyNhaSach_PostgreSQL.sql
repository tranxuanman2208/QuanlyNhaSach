    CONSTRAINT "PK__PHIEUXUA__2725E7F2" PRIMARY KEY ("MaPX"),
    CONSTRAINT "FK_MaDH" FOREIGN KEY ("MaDH") REFERENCES "DONHANG" ("MaDH")
);

